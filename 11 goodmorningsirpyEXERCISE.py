import time
timestamps=time.strftime("%Y-%m-%d %H:%M:%S")
print("the time is:",timestamps) #prints the current date and time in the format of YYYY-MM-DD HH:MM:SS
timestamps=time.strftime("%H")
print(timestamps) #prints the current hour in 24-hour format
timestamps=time.strftime("%M")
print(timestamps) #prints the current minute
timestamps=time.strftime("%S")
print(timestamps) #prints the current second